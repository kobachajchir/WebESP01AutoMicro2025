export function buildBitmapTextPath(
  text: string,
  font: OledFont,
  x: number,
  y: number,
  align: "left" | "center" | "right" = "left",
) {
  const config = FONT_CONFIG[font];
  const lines = (text || "").split("\n");
  const maxColumns = Math.max(
    0,
    ...lines.map((line) => Array.from(line).length * config.width),
  );
  const segments: string[] = [];

  lines.forEach((line, lineIndex) => {
    const glyphs = Array.from(line);
    const lineWidth = glyphs.length * config.width;
    const originX =
      align === "center"
        ? x - Math.floor(lineWidth / 2)
        : align === "right"
          ? x - lineWidth
          : x;
    const originY = y + lineIndex * (config.height + 1);

    glyphs.forEach((char, glyphIndex) => {
      const rows = getGlyphRows(font, char);
      rows.forEach((row, rowIndex) => {
        for (let pixelIndex = 0; pixelIndex < config.width; pixelIndex += 1) {
          const bitIndex = config.bitStart - pixelIndex;
          if (((row >> bitIndex) & 0x01) === 0) {
            continue;
          }

          const pixelX = originX + glyphIndex * config.width + pixelIndex;
          const pixelY = originY + rowIndex;
          segments.push(
            `M${pixelX} ${pixelY}h1v1h-1Z`,
          );
        }
      });
    });
  });

  return {
    width: maxColumns,
    height:
      lines.length === 0
        ? config.height
        : lines.length * config.height + Math.max(0, lines.length - 1),
    path: segments.join(""),
  };
}

export function getGlyphRows(font: OledFont, char: string) {
  const config = FONT_CONFIG[font];
  const safeChar = normalizeGlyphChar(char);
  const glyphIndex = safeChar.charCodeAt(0) - 32;
  const offset = glyphIndex * config.rowsPerGlyph;
  return config.data.slice(offset, offset + config.rowsPerGlyph);
}

function normalizeGlyphChar(char: string) {
  const fallback = "?";
  const candidate = Array.from(char || fallback)[0] ?? fallback;
  const code = candidate.charCodeAt(0);
  return code >= 32 && code <= 126 ? candidate : fallback;
}

function parseHexNumbers(source: string) {
  return (source.match(/0x[0-9a-fA-F]+/g) ?? []).map((token) =>
    Number.parseInt(token.slice(2), 16),
  );
}
